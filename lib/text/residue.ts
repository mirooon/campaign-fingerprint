/**
 * Leftovers and foreign inserts in the text of a page (B-306, B-307, B-308). Operators copy pages and
 * scripts between countries and versions, and the seams stay: a commented-out old paragraph, a disclaimer
 * in another language, a doctor's title of another country in the ad name. All of it is an attribute for
 * the reviewer ("trace of another version"), never a weight, and says nothing about who wrote it.
 * Pure functions, no network access.
 */

/** Languages the block detector knows; alphabets are told apart by script, Latin ones by function words. */
export type TextLang = "pl" | "en" | "it" | "es" | "fr" | "de" | "cs" | "sk" | "ro" | "hu" | "pt" | "ru" | "uk" | "bg" | "bn" | "vi" | "el" | "hy" | "ka";

export const RESIDUE_CONFIG = {
  /** A comment counts as a commented-out text from this many words. */
  residueMinWords: 8,
  /** Share of letters and spaces in the comment (code has braces, equals signs and semicolons). */
  residueMinLetterShare: 0.8,
  /** Licence, authorship and tool comments (and the marker of the synthetic page generator) are not leftovers. */
  residueIgnore: /licen[cs]|copyright|\(c\)|©|all rights reserved|@preserve|@author|generated by|sourcemappingurl|eslint|webpack|apache|mit license|todo\b|fixme|starter hacknation/i,
  maxSampleChars: 120,
  /** Latin-script blocks need at least this many letters, others (own alphabets) this many. */
  minLatinChars: 40,
  minScriptChars: 12,
  /** A block with at least this many comma-separated short items is a list (countries, cities), not a sentence. */
  listMinItems: 5,
  maxSegments: 12,
  /** Function words per Latin-script language (lower case, no diacritics folding). */
  functionWords: {
    pl: ["i", "w", "nie", "się", "na", "to", "jest", "że", "do", "z", "jak", "który", "dla", "przez", "oraz", "są", "od", "po", "tylko", "lub"],
    en: ["the", "and", "of", "to", "is", "in", "for", "with", "you", "your", "that", "this", "are", "on", "not", "by", "be", "we"],
    it: ["il", "di", "che", "per", "non", "della", "delle", "una", "sono", "con", "gli", "nel", "anche", "dei", "è", "alla", "dal"],
    es: ["el", "los", "las", "que", "y", "en", "un", "una", "por", "con", "para", "del", "es", "se", "su", "al"],
    fr: ["le", "les", "des", "et", "est", "une", "pour", "dans", "que", "pas", "vous", "du", "sur", "au", "ce", "qui"],
    de: ["der", "die", "das", "und", "nicht", "ist", "ein", "eine", "mit", "für", "den", "von", "zu", "sie", "auf", "dem"],
    cs: ["je", "se", "na", "že", "ve", "jsou", "pro", "který", "jako", "nebo", "aby", "byl", "si", "tato", "jsme", "také"],
    sk: ["je", "sa", "na", "že", "nie", "pre", "ktorý", "ako", "alebo", "aby", "som", "sú", "tento", "aj", "len"],
    ro: ["și", "de", "în", "cu", "pentru", "este", "care", "nu", "la", "un", "o", "din", "sunt", "să", "mai", "pe"],
    hu: ["a", "az", "és", "hogy", "nem", "van", "egy", "ez", "meg", "csak", "vagy", "is", "de", "már"],
    pt: ["o", "os", "as", "que", "e", "em", "um", "uma", "para", "com", "não", "do", "da", "dos", "por", "é"],
  } as Record<string, string[]>,
  /** Letters that mark a language on their own (each hit counts double). */
  marker: {
    pl: /[ąęłńśźż]/g,
    cs: /[ěřůťďň]/g,
    sk: /[ĺľŕôä]/g,
    ro: /[ăşţșț]/g,
    hu: /[őű]/g,
    de: /[ßäöü]/g,
    es: /[ñ¿¡]/g,
    fr: /[èêçœàùû]/g,
    pt: /[ãõ]/g,
    it: /[ìò]/g,
  } as Record<string, RegExp>,
  /** Tracking parameters in whose values a foreign persona is looked for. */
  personaParams: ["ad_name", "adset_name", "campaign_name"],
  /** Country code of the market in the ad name (PL) and professional titles per language. */
  marketCode: /(?:^|[\s/_|\-.:])PL(?:$|[\s/_|\-.:])/,
  personaTitles: [
    { re: /\bMUDr\.?/, title: "MUDr.", lang: "cs" },
    { re: /\bMVDr\.?/, title: "MVDr.", lang: "cs" },
    { re: /\bDr\.?\s?med\.?/i, title: "Dr. med.", lang: "de" },
    { re: /\bDott(?:\.|ssa\b)/, title: "Dott.", lang: "it" },
    { re: /\bProf\.\s?Dr\./, title: "Prof. Dr.", lang: "de" },
    { re: /\bIng\./, title: "Ing.", lang: "cs/sk" },
    { re: /\bDipl\.-?\s?\w+/, title: "Dipl.", lang: "de" },
  ] as Array<{ re: RegExp; title: string; lang: string }>,
  personaLetters: [
    { re: /[ěřůťďň]/i, lang: "cs" },
    { re: /[ĺľŕô]/i, lang: "sk" },
    { re: /[őű]/i, lang: "hu" },
    { re: /[ăşţșț]/i, lang: "ro" },
    { re: /[ß]/, lang: "de" },
  ] as Array<{ re: RegExp; lang: string }>,
};

export interface Residue {
  /** Number of commented-out texts. */
  count: number;
  /** The first one, cut to `maxSampleChars`. */
  sample: string;
  /** All of them (cut), for the template-phrase source "from a comment". */
  texts: string[];
}

/**
 * Commented-out old text: comments (already normalised by the page kit) of at least `residueMinWords`
 * words that read as sentences, not code and not a licence. Null when there is none.
 */
export function residueOf(comments: string[]): Residue | null {
  const c = RESIDUE_CONFIG;
  const texts: string[] = [];
  for (const raw of comments) {
    const text = raw.replace(/\s+/g, " ").trim();
    if (text.split(" ").length < c.residueMinWords || c.residueIgnore.test(text)) continue;
    const plain = text.replace(/[^\p{L}\s.,!?:;'"„”«»\-–—…()0-9%]/gu, "");
    if (plain.length / text.length < c.residueMinLetterShare || /[{};=<>]|=>|\(\)|\bfunction\b|\bvar\b/.test(text)) continue;
    texts.push(text.slice(0, 400));
  }
  return texts.length ? { count: texts.length, sample: texts[0].slice(0, c.maxSampleChars), texts } : null;
}

/** Language of an alphabet other than Latin, or null for Latin text. Cyrillic is split by its distinctive letters. */
function scriptLang(text: string): TextLang | null {
  const count = (re: RegExp) => (text.match(re) ?? []).length;
  const letters = count(/\p{L}/gu) || 1;
  const cyr = count(/[Ѐ-ӿ]/g);
  if (cyr / letters > 0.5) {
    if (count(/[іїєґІЇЄҐ]/g) > 0) return "uk";
    if (count(/[ыэёЫЭЁ]/g) > 0) return "ru";
    if (count(/[ъЪ]/g) > 0) return "bg";
    return "ru";
  }
  if (count(/[ঀ-৿]/g) / letters > 0.5) return "bn";
  if (count(/[Ͱ-Ͽ]/g) / letters > 0.5) return "el";
  if (count(/[԰-֏]/g) / letters > 0.5) return "hy";
  if (count(/[Ⴀ-ჿ]/g) / letters > 0.5) return "ka";
  return null;
}

/**
 * Language of a block of text: an own alphabet by its script, a Latin language by function words and
 * letters of its own (best score, clearly ahead of the second). Null for a block too short or unclear.
 */
export function detectLang(text: string): TextLang | null {
  const c = RESIDUE_CONFIG;
  const letters = (text.match(/\p{L}/gu) ?? []).length;
  const alt = scriptLang(text);
  if (alt) return letters >= c.minScriptChars ? alt : null;
  if (letters < c.minLatinChars) return null;
  const words = text.toLowerCase().match(/[\p{L}]+/gu) ?? [];
  // Vietnamese: stacked diacritics on Latin letters are unique to it
  const vi = (text.match(/[ạảấầẩẫậắằẳẵặẹẻẽếềểễệỉịọỏốồổỗộớờởỡợụủứừửữựỳỵỷỹơưđ]/giu) ?? []).length;
  if (vi >= 4 && vi / words.length > 0.2) return "vi";
  const scores: Array<[string, number]> = [];
  for (const [lang, list] of Object.entries(c.functionWords)) {
    const set = new Set(list);
    let s = words.filter((w) => set.has(w)).length;
    const mark = c.marker[lang];
    if (mark) s += 2 * Math.min(3, (text.toLowerCase().match(mark) ?? []).length);
    scores.push([lang, s]);
  }
  scores.sort((a, b) => b[1] - a[1]);
  const [best, second] = scores;
  if (best[1] < 3 || best[1] < second[1] * 1.4 || best[1] / words.length < 0.12) return null;
  return best[0] as TextLang;
}

/** True for a line that lists names (countries, cities, languages): many short comma-separated items. */
function isNameList(block: string): boolean {
  const items = block.split(/[,;|·•\n]/).map((s) => s.trim()).filter(Boolean);
  return items.length >= RESIDUE_CONFIG.listMinItems && items.every((i) => i.split(/\s+/).length <= 3);
}

export interface ForeignSegment {
  lang: TextLang;
  where: "page" | "script" | "comment" | "ad_param";
  /** Letters in the blocks of this language at this place. */
  chars: number;
  /** The first block, cut to `maxSampleChars`. */
  sample: string;
}

export interface ForeignSegmentInput {
  page?: string | null;
  scripts?: string[];
  comments?: string[];
  adParams?: string[];
}

/**
 * Blocks of text in a language other than the main one (the language of the whole page, Polish when it
 * cannot be told), per language and place. Country lists, language switchers (too short) and interface
 * dictionaries (the caller leaves them out) are not segments. Empty when everything is in one language.
 */
export function foreignSegments(input: ForeignSegmentInput): ForeignSegment[] {
  const c = RESIDUE_CONFIG;
  const pageBlocks = (input.page ?? "").split(/\n+|(?<=[.!?…])\s+/).map((s) => s.trim()).filter(Boolean);
  const main: TextLang = detectLang(pageBlocks.join("\n")) ?? "pl";
  const found = new Map<string, ForeignSegment>();
  const take = (blocks: string[], where: ForeignSegment["where"]) => {
    for (const block of blocks) {
      if (isNameList(block)) continue;
      const lang = detectLang(block);
      if (!lang || lang === main) continue;
      const chars = (block.match(/\p{L}/gu) ?? []).length;
      const key = `${lang}|${where}`;
      const prev = found.get(key);
      if (prev) prev.chars += chars;
      else if (found.size < c.maxSegments) found.set(key, { lang, where, chars, sample: block.replace(/\s+/g, " ").slice(0, c.maxSampleChars) });
    }
  };
  take(pageBlocks, "page");
  take(input.scripts ?? [], "script");
  take(input.comments ?? [], "comment");
  take(input.adParams ?? [], "ad_param");
  return [...found.values()].sort((a, b) => b.chars - a.chars);
}

export interface ForeignPersona {
  title: string;
  lang: string;
  /** The tracking parameter it was found in. */
  param: string;
}

/**
 * A professional title or letters of another language in the ad, ad-set or campaign name of an ad that
 * carries the Polish market code (`PL`): a persona prepared for another country. `params` are
 * [canonical name, value] pairs; `polish` says the landing page or ad is Polish when the name has no code.
 */
export function foreignPersona(params: Array<[string, string]>, polish = false): ForeignPersona[] {
  const c = RESIDUE_CONFIG;
  const out: ForeignPersona[] = [];
  for (const [name, value] of params) {
    if (!c.personaParams.includes(name) || (!polish && !c.marketCode.test(value))) continue;
    const t = c.personaTitles.find((x) => x.re.test(value));
    if (t) {
      out.push({ title: t.title, lang: t.lang, param: name });
      continue;
    }
    const letter = c.personaLetters.find((x) => x.re.test(value));
    if (letter) {
      const word = value.split(/[\s/_|]+/).find((w) => letter.re.test(w)) ?? value;
      out.push({ title: word.slice(0, 40), lang: letter.lang, param: name });
    }
  }
  return out;
}
